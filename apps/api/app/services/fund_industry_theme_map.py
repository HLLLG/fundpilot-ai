def map_industry_to_theme_label(industry: str | None) -> str | None:
    """将个股所属行业映射到粗粒度主题板块名；映射不到可交易板块时返回 None。"""
    normalized = normalize_sector_label(industry)
    if not normalized:
        return None

    if normalized in THEME_BOARD_WHITELIST:
        return normalized

    mapped = _INDUSTRY_TO_THEME.get(normalized)
    if mapped is not None:
        return mapped

    canon = get_canonical_sector(normalized)
    if canon is not None:
        return canon.label

    best: str | None = None
    best_len = 0
    for label in THEME_BOARD_WHITELIST:
        if label in normalized or normalized in label:
            if len(label) > best_len:
                best = label
                best_len = len(label)
    if best is not None:
        return best

    # 归并不到任何可交易板块时返回 None（fail-closed）。
    #
    # 历史实现在这里直接把数据源的原始行业名当主题返回，理由是"不丢掉这只重仓股的
    # 投票权重"。但这个 label 没有行情标的，一旦它成为基金的主板块，页面就只有板块名
    # 没有涨跌幅——而用户看这一栏就是为了拿涨跌幅对照自己的基金。实测有 3292 行主板块
    # 落在这种 label 上（其中 140 行是决策级 verified），最多的"通信设备"占 1281 只。
    # 现在改为不计票：该股的权重不进入 classified_mass，若可分类比例因此不达标，
    # 基金会停在 research_only 而不是顶着一个不可定价的板块名。
    return None
